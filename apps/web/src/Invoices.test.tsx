const today = todaySast();
const month = nextMonthStart(today);

const inv = (over: Partial<Invoice> & { id: string }): Invoice => ({
  clientId: 'c1',
  clientName: 'Dan Dillon',
  clientEmail: 'dan@example.com',
  number: 'AF-202612-001',
  periodStart: month,
  issuedOn: today,
  dueOn: month,
  status: 'draft',
  vatPercent: 0,
  subtotal: 135000,
  vat: 0,
  total: 135000,
  notes: 'Sessions: 1 Dec 07:00, 8 Dec 07:00, 15 Dec 07:00',
  autoGenerated: false,
  emailQueuedAt: null,
  emailedAt: null,
  paidAt: null,
  paidMethod: null,
  lines: [
    {
      id: 'l1',
      description: 'Training session, December 2026',
      quantity: 3,
      unitCents: 45000,
      amountCents: 135000,
    },
  ],
  ...over,
});

const clientRec = (id: string, name: string, whatsapp = ''): ClientRecord =>
  ({
    client: { id, name, whatsapp },
    consents: [],
    programmes: [],
    createdAt: '2026-01-01T00:00:00Z',
  }) as unknown as ClientRecord;

function fakeApi(initial: Invoice[] = [], settings: Partial<ReturnType<typeof defaultInvoiceSettings>> = {}) {
  let rows = [...initial];
  let rates: ClientRate[] = [
    { clientId: 'c1', name: 'Dan Dillon', rateCents: 45000 },
    { clientId: 'c2', name: 'Eve Evans', rateCents: null },
  ];
  const api: InvoicesApi = {
    settings: vi.fn(async () => ({
      ...defaultInvoiceSettings(),
      defaultRate: 40000,
      bankDetails: 'FNB 123456',
      businessName: 'Alice Fitness',
      address: '1 Main Rd',
      email: 'a@x.com',
      phone: '',
      ...settings,
    })),
    saveSettings: vi.fn(async () => {}),
    rates: vi.fn(async () => rates),
    setRate: vi.fn(async (id: string, cents: number | null) => {
      rates = rates.map((r) => (r.clientId === id ? { ...r, rateCents: cents } : r));
    }),
    list: vi.fn(async () => rows),
    generate: vi.fn(async (m: string) => {
      rows = [...rows, inv({ id: 'new', periodStart: m, number: 'AF-NEW-001' })];
      return {
        month: m,
        generated: 1,
        invoiceIds: ['new'],
        skippedNoRate: ['Eve Evans'],
        skippedExisting: 2,
        skippedNoSessions: 3,
      };
    }),
    addLine: vi.fn(async () => {}),
    updateLine: vi.fn(async () => {}),
    removeLine: vi.fn(async () => {}),
    setStatus: vi.fn(async (id: string, status: 'draft' | 'sent' | 'void') => {
      rows = rows.map((r) => (r.id === id ? { ...r, status } : r));
    }),
    markPaid: vi.fn(async (id: string) => {
      rows = rows.map((r) =>
        r.id === id
          ? { ...r, status: 'paid' as const, paidMethod: 'eft' as const, paidAt: `${today}T10:00:00Z` }
          : r,
      );
    }),
    markUnpaid: vi.fn(async (id: string) => {
      rows = rows.map((r) =>
        r.id === id ? { ...r, status: 'sent' as const, paidMethod: null, paidAt: null } : r,
      );
    }),
    email: vi.fn(async () => true),
    removeDraft: vi.fn(async (id: string) => {
      rows = rows.filter((r) => r.id !== id);
    }),
  };
  return api;
}

function mount(api = fakeApi([inv({ id: 'a' })]), say = vi.fn()) {
  render(<InvoicesTab api={api} clients={[clientRec('c1', 'Dan Dillon', '082 555 0100')]} say={say} />);
  return { api, say };
}

beforeEach(() => localStorage.clear());

describe('the Invoices tab', () => {
  it('opens on next month, listing its invoices with client, number, due date, amount and status', async () => {
    mount();
    const card = await screen.findByRole('listitem', { name: 'Invoice AF-202612-001' });
    expect(card).toHaveTextContent('Dan Dillon');
    expect(card).toHaveTextContent(/R1.350,00/);
    expect(card).toHaveTextContent('Draft');
    expect(screen.getByRole('heading', { name: /\d{4}$/ })).toBeInTheDocument();
  });

  it('shows what is owed and what is overdue, across all months', async () => {
    mount(
      fakeApi([
        inv({ id: 'a', status: 'sent', dueOn: addMonths(today.slice(0, 7) + '-01', -1) }),
        inv({ id: 'b', status: 'sent', number: 'N2', total: 50000 }),
        inv({ id: 'c', status: 'paid', number: 'N3' }),
      ]),
    );
    expect(
      await screen.findByText((t) =>
        /^Owed to you: R1\s850,00 across 2 invoices, of which R1\s350,00 is overdue \(1\)/.test(
          t.replace(/[\u00a0\s]/g, ' '),
        ),
      ),
    ).toBeInTheDocument();
  });

  it('makes the month’s invoices and says who was skipped and why', async () => {
    const { api } = mount(fakeApi([]));
    await screen.findByText(/No invoices for/);
    fireEvent.click(screen.getByRole('button', { name: /^Make the .* invoices$/ }));
    await waitFor(() => expect(api.generate).toHaveBeenCalledWith(month));
    const out = await screen.findByRole('status', { name: 'What was made' });
    expect(out).toHaveTextContent('Made 1 invoice as drafts');
    expect(out).toHaveTextContent('2 clients already have an invoice');
    expect(out).toHaveTextContent('3 clients have no sessions booked');
    expect(out).toHaveTextContent('No rate set for Eve Evans');
    expect(await screen.findByRole('listitem', { name: 'Invoice AF-NEW-001' })).toBeInTheDocument();
  });

  it('a draft’s lines can be edited, added to and removed', async () => {
    const { api } = mount();
    const card = await screen.findByRole('listitem', { name: 'Invoice AF-202612-001' });
    const price = within(card).getByLabelText('Price (R)');
    fireEvent.change(price, { target: { value: '500,50' } });
    fireEvent.blur(price);
    await waitFor(() =>
      expect(api.updateLine).toHaveBeenCalledWith('l1', {
        description: 'Training session, December 2026',
        quantity: 3,
        unitCents: 50050,
      }),
    );
    fireEvent.change(within(card).getByLabelText('Price (R)'), { target: { value: 'abc' } });
    fireEvent.blur(within(card).getByLabelText('Price (R)'));
    expect(api.updateLine).toHaveBeenCalledTimes(1);
    fireEvent.click(within(card).getByRole('button', { name: 'Add a line' }));
    await waitFor(() =>
      expect(api.addLine).toHaveBeenCalledWith('a', 2, {
        description: 'Adjustment',
        quantity: 1,
        unitCents: 0,
      }),
    );
    fireEvent.click(within(card).getByRole('button', { name: /^Remove line/ }));
    await waitFor(() => expect(api.removeLine).toHaveBeenCalledWith('l1'));
  });

  it('sending marks it sent and emails it; if email is not set up the trainer is told what to do instead', async () => {
    const { api, say } = mount();
    fireEvent.click(await screen.findByRole('button', { name: 'Send to client' }));
    await waitFor(() => expect(api.setStatus).toHaveBeenCalledWith('a', 'sent'));
    expect(api.email).toHaveBeenCalledWith('a');
    await waitFor(() =>
      expect(say).toHaveBeenCalledWith('Invoice AF-202612-001 emailed to dan@example.com.'),
    );
    vi.mocked(api.email).mockResolvedValueOnce(false);
    fireEvent.click(await screen.findByRole('button', { name: 'Email again' }));
    await waitFor(() => expect(say).toHaveBeenCalledTimes(2));
    expect(say.mock.calls[1]![0]).toMatch(/The email could not be sent \(email is not set up yet\)/);
  });

  it('a sent invoice has a WhatsApp link with the amount and the bank details, and locks the lines', async () => {
    mount(fakeApi([inv({ id: 'a', status: 'sent' })]));
    const link = await screen.findByRole('link', { name: 'Send on WhatsApp' });
    expect(link.getAttribute('href')).toMatch(/^https:\/\/wa\.me\/27825550100\?text=/);
    const text = decodeURIComponent(link.getAttribute('href')!);
    expect(text).toMatch(/R1.350,00/);
    expect(text).toContain('FNB 123456');
    expect(text).toContain('AF-202612-001 as the payment reference');
    expect(screen.queryByLabelText('Price (R)')).toBeNull();
  });

  it('marking paid records how and when; and it can be undone', async () => {
    const { api } = mount(fakeApi([inv({ id: 'a', status: 'sent' })]));
    fireEvent.click(await screen.findByRole('button', { name: 'Mark as paid' }));
    const form = screen.getByLabelText('Record payment');
    fireEvent.change(within(form).getByLabelText('Paid by'), { target: { value: 'cash' } });
    fireEvent.click(within(form).getByRole('button', { name: 'Save payment' }));
    await waitFor(() => expect(api.markPaid).toHaveBeenCalledWith('a', 'cash', today));
    expect(await screen.findByText(/Paid · EFT/)).toBeInTheDocument();
    fireEvent.click(screen.getByRole('button', { name: 'Mark as not paid' }));
    await waitFor(() => expect(api.markUnpaid).toHaveBeenCalledWith('a'));
  });

  it('cancelling an invoice and deleting a draft each take two taps', async () => {
    const { api } = mount();
    fireEvent.click(await screen.findByRole('button', { name: 'Cancel invoice AF-202612-001' }));
    expect(api.setStatus).not.toHaveBeenCalled();
    fireEvent.click(screen.getByRole('button', { name: 'Tap again to confirm' }));
    await waitFor(() => expect(api.setStatus).toHaveBeenCalledWith('a', 'void'));
  });

  it('an invoice waiting to be emailed says so', async () => {
    mount(
      fakeApi([inv({ id: 'a', status: 'sent', autoGenerated: true, emailQueuedAt: `${today}T05:00:00Z` })]),
    );
    expect(await screen.findByText(/waiting to be emailed/)).toBeInTheDocument();
    expect(screen.getByText(/made automatically/)).toBeInTheDocument();
  });

  it('rates per client are saved when the field is left; blank means the default', async () => {
    const { api } = mount();
    fireEvent.click(await screen.findByText('Rates per client'));
    const eve = screen.getByLabelText('Rate for Eve Evans');
    fireEvent.change(eve, { target: { value: '375' } });
    fireEvent.blur(eve);
    await waitFor(() => expect(api.setRate).toHaveBeenCalledWith('c2', 37500));
    const dan = screen.getByLabelText('Rate for Dan Dillon');
    fireEvent.change(dan, { target: { value: '' } });
    fireEvent.blur(dan);
    await waitFor(() => expect(api.setRate).toHaveBeenCalledWith('c1', null));
  });

  it('settings: refuses a bad payment link, saves good ones, and explains the automatic run in plain words', async () => {
    const { api } = mount(fakeApi([], { auto: true, daysBefore: 5 }));
    fireEvent.click(await screen.findByText('Invoice settings'));
    expect(screen.getByText(/This month’s run is on/)).toHaveTextContent('They wait as drafts');
    fireEvent.change(screen.getByLabelText(/Payment link/), { target: { value: 'http://insecure' } });
    fireEvent.click(screen.getByRole('button', { name: 'Save settings' }));
    expect(await screen.findByRole('alert')).toHaveTextContent('must start with https://');
    expect(api.saveSettings).not.toHaveBeenCalled();
    fireEvent.change(screen.getByLabelText(/Payment link/), { target: { value: 'https://pay.example/a' } });
    fireEvent.change(screen.getByLabelText(/^Default rate per session/), { target: { value: '450' } });
    fireEvent.click(screen.getByLabelText('Send them to clients without checking first'));
    fireEvent.click(screen.getByRole('button', { name: 'Save settings' }));
    await waitFor(() => expect(api.saveSettings).toHaveBeenCalledTimes(1));
    expect(vi.mocked(api.saveSettings).mock.calls[0]![0]).toMatchObject({
      defaultRate: 45000,
      paymentLink: 'https://pay.example/a',
      autoSend: true,
      auto: true,
    });
  });
});

describe('the invoice file and email', () => {
  const sample = inv({
    id: 'a',
    vatPercent: 15,
    subtotal: 100000,
    vat: 15000,
    total: 115000,
    status: 'sent',
  });
  const from = { name: 'Alice Fitness', address: '1 Main Rd', email: 'a@x.com', phone: '' };
  it('makes a one-page PDF with the number, lines, VAT and how to pay', () => {
    const doc = buildInvoicePdf(
      pdfModelFromInvoice(sample, from, {
        bankDetails: 'FNB 123456',
        paymentLink: 'https://pay.example/a',
        terms: 'Pay before the 1st',
      }),
    );
    expect(doc.getNumberOfPages()).toBe(1);
    const raw = doc.output();
    expect(raw).toContain('AF-202612-001');
    expect(raw).toContain('VAT');
    expect(raw).toContain('15%');
    expect(raw).toContain('FNB 123456');
    expect(raw.startsWith('%PDF')).toBe(true);
  });
  it('a paid invoice says paid and drops the how-to-pay block', () => {
    const raw = buildInvoicePdf(
      pdfModelFromInvoice({ ...sample, status: 'paid' }, from, {
        bankDetails: 'FNB 123456',
        paymentLink: '',
        terms: '',
      }),
    ).output();
    expect(raw).toContain('PAID');
    expect(raw).not.toContain('HOW TO PAY');
  });
  it('the client’s copy is the same page', () => {
    const m = pdfModelFromPortal(
      {
        id: 'i',
        number: 'N-1',
        periodStart: month,
        issuedOn: today,
        dueOn: month,
        status: 'sent',
        vatPercent: 0,
        subtotal: 100,
        vat: 0,
        total: 100,
        notes: '',
        paidAt: null,
        trainerName: 'AF',
        trainerAddress: '',
        trainerEmail: '',
        trainerPhone: '',
        pay: { bankDetails: '', paymentLink: '', terms: '' },
        lines: [{ description: 'S', quantity: 1, unitCents: 100, amountCents: 100 }],
      },
      'Dan Dillon',
    );
    expect(m.billTo.name).toBe('Dan Dillon');
    expect(buildInvoicePdf(m).getNumberOfPages()).toBe(1);
  });
  it('the email has the amount, due date, both ways to pay, and escapes anything risky', () => {
    const m = invoiceEmail({
      trainerName: 'Alice <Fit>',
      clientName: 'Dan Dillon',
      number: 'N-1',
      monthLabel: 'December 2026',
      total: 'R1 800,00',
      due: 'Tuesday 1 December 2026',
      lines: [{ description: 'Sessions', amount: 'R1 800,00' }],
      bankDetails: 'FNB\n123',
      paymentLink: 'https://pay.example/a',
      terms: '',
      portalUrl: 'https://app.example/portal',
      productName: 'PT Planner',
    });
    expect(m.subject).toBe('Invoice N-1 from Alice <Fit>: R1 800,00 for December 2026');
    expect(m.text).toContain('Pay online: https://pay.example/a');
    expect(m.text).toContain('Use N-1 as the payment reference.');
    expect(m.html).toContain('Alice &lt;Fit&gt;');
    expect(m.html).toContain('FNB<br>123');
  });
});

describe('the client’s invoices', () => {
  const SESSION = { user: { id: 'u1', email: 'dan@example.com' } } as unknown as Session;
  const overview = {
    email: 'dan@example.com',
    memberships: [
      {
        client_id: 'c1',
        client_name: 'Dan Dillon',
        trainer: {
          business_name: 'Alice Fitness',
          display_name: 'a',
          address: '',
          contact_email: '',
          contact_phone: '',
          information_officer_name: '',
          information_officer_email: '',
        },
        programmes: [],
        consents: [],
      },
    ],
  };
  const row = (id: string, over: Record<string, unknown> = {}) => ({
    id,
    client_id: 'c1',
    number: `N-${id}`,
    period_start: month,
    issued_on: today,
    due_on: addMonths(today.slice(0, 7) + '-01', 1),
    status: 'sent',
    vat_percent: 0,
    subtotal_cents: 135000,
    vat_cents: 0,
    total_cents: 135000,
    notes: '',
    paid_at: null,
    trainer: {
      business_name: 'Alice Fitness',
      address: '',
      contact_email: '',
      contact_phone: '',
      bank_details: 'FNB 123456',
      payment_link: 'https://pay.example/a',
      terms: '',
    },
    lines: [{ description: 'Training session', quantity: 3, unit_cents: 45000, amount_cents: 135000 }],
    ...over,
  });
  async function open(rows: unknown[]) {
    const rpc = vi.fn(async (name: string) => ({
      data: name === 'portal_overview' ? overview : name === 'portal_invoices' ? rows : null,
      error: null,
    }));
    const client = {
      auth: {
        getSession: vi.fn().mockResolvedValue({ data: { session: SESSION } }),
        onAuthStateChange: vi.fn().mockReturnValue({ data: { subscription: { unsubscribe: vi.fn() } } }),
      },
      rpc,
    } as unknown as SupabaseClient;
    render(<App client={client} pathname="/portal" />);
    fireEvent.click(await screen.findByRole('tab', { name: 'My invoices' }));
    return rpc;
  }

  it('shows what is owed and exactly how to pay, with the invoice number as the reference', async () => {
    await open([row('1')]);
    expect(await screen.findByText(/You owe R1.350,00/)).toBeInTheDocument();
    expect(screen.getByText(/FNB 123456\s*Reference: N-1/)).toBeInTheDocument();
    expect(screen.getByRole('link', { name: 'Pay online' })).toHaveAttribute('href', 'https://pay.example/a');
    expect(screen.getByRole('button', { name: 'Save as PDF' })).toBeInTheDocument();
  });

  it('a paid invoice shows as paid with no payment details', async () => {
    await open([row('2', { status: 'paid', paid_at: `${today}T10:00:00Z` })]);
    expect(await screen.findByText(/Paid$/)).toBeInTheDocument();
    expect(screen.queryByText('How to pay')).toBeNull();
    expect(screen.queryByText(/You owe/)).toBeNull();
  });

  it('says so when there are none', async () => {
    await open([]);
    expect(await screen.findByText('No invoices yet')).toBeInTheDocument();
  });
});
