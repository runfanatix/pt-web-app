import { describe, expect, it } from 'vitest';
import {
  InvoiceSettingsSchema,
  autoInvoiceDay,
  defaultInvoiceSettings,
  invoiceMessage,
  invoiceTotals,
  isOverdue,
  monthLabel,
  nextMonthStart,
  outstanding,
  parseGenerationSummary,
  parseInvoices,
  parsePortalInvoices,
  parseRand,
  rand,
  settingsFromRow,
  settingsToRow,
  type Invoice,
} from './index.ts';

describe('rand', () => {
  it('shows South African style, with cents always', () => {
    expect(rand(0)).toBe('R0,00');
    expect(rand(5)).toBe('R0,05');
    expect(rand(45000)).toBe('R450,00');
    expect(rand(123456)).toBe('R1 234,56');
    expect(rand(-10000)).toBe('-R100,00');
    expect(rand(100000000)).toBe('R1 000 000,00');
  });
  it('reads what a person types', () => {
    expect(parseRand('450')).toBe(45000);
    expect(parseRand('R 1 200,5')).toBe(120050);
    expect(parseRand('450.75')).toBe(45075);
    expect(parseRand('-100')).toBe(-10000);
    expect(parseRand('4,5,0')).toBeNull();
    expect(parseRand('')).toBeNull();
    expect(parseRand('abc')).toBeNull();
    expect(parseRand('1.234')).toBeNull();
  });
});

describe('totals', () => {
  it('quantity times price per line, VAT on the subtotal, rounded to the cent', () => {
    expect(
      invoiceTotals(
        [
          { description: 'a', quantity: 3, unitCents: 45000 },
          { description: 'b', quantity: 1, unitCents: 45000 },
        ],
        15,
      ),
    ).toEqual({ subtotal: 180000, vat: 27000, total: 207000 });
    expect(invoiceTotals([{ description: 'a', quantity: 1.5, unitCents: 33333 }], 0)).toEqual({
      subtotal: 50000,
      vat: 0,
      total: 50000,
    });
    expect(invoiceTotals([{ description: 'a', quantity: 1, unitCents: 999 }], 15)).toEqual({
      subtotal: 999,
      vat: 150,
      total: 1149,
    });
    expect(invoiceTotals([], 15).total).toBe(0);
  });
});

describe('settings', () => {
  it('accepts the defaults and a full set, and refuses nonsense in plain words', () => {
    expect(InvoiceSettingsSchema.safeParse(defaultInvoiceSettings()).success).toBe(true);
    const bad = InvoiceSettingsSchema.safeParse({
      ...defaultInvoiceSettings(),
      prefix: 'no spaces',
      paymentLink: 'http://x',
      vatPercent: 120,
      daysBefore: 30,
    });
    expect(bad.success).toBe(false);
    if (!bad.success) expect(bad.error.issues.length).toBe(4);
    expect(
      InvoiceSettingsSchema.safeParse({ ...defaultInvoiceSettings(), paymentLink: 'https://pay.example/a' })
        .success,
    ).toBe(true);
  });
  it('round trips through the database row', () => {
    const s = {
      ...defaultInvoiceSettings(),
      defaultRate: 45000,
      vatPercent: 15,
      prefix: ' AF ',
      bankDetails: ' FNB ',
      auto: true,
      daysBefore: 7,
      autoSend: true,
    };
    const row = settingsToRow(s);
    expect(row).toMatchObject({
      default_rate_cents: 45000,
      vat_percent: 15,
      invoice_prefix: 'AF',
      bank_details: 'FNB',
      auto_invoice: true,
      invoice_days_before: 7,
      auto_send: true,
    });
    expect(settingsFromRow(row)).toEqual({ ...s, prefix: 'AF', bankDetails: 'FNB' });
    expect(settingsFromRow({ ...row, vat_percent: '15.00' }).vatPercent).toBe(15);
  });
  it('the automatic day is that many days before the month ends', () => {
    expect(autoInvoiceDay('2026-12-10', 5)).toBe('2026-12-26');
    expect(autoInvoiceDay('2026-02-03', 0)).toBe('2026-02-28');
    expect(autoInvoiceDay('2028-02-03', 5)).toBe('2028-02-24');
    expect(nextMonthStart('2026-12-17')).toBe('2027-01-01');
    expect(monthLabel('2027-01-01')).toBe('January 2027');
  });
});

const inv = (over: Partial<Invoice> & { id: string }): Invoice => ({
  clientId: 'c',
  clientName: 'Dan Dillon',
  clientEmail: 'd@x.com',
  number: 'AF-202612-001',
  periodStart: '2026-12-01',
  issuedOn: '2026-11-26',
  dueOn: '2026-12-01',
  status: 'sent',
  vatPercent: 0,
  subtotal: 100000,
  vat: 0,
  total: 100000,
  notes: '',
  autoGenerated: false,
  emailQueuedAt: null,
  emailedAt: null,
  paidAt: null,
  paidMethod: null,
  lines: [],
  ...over,
});

describe('what is owed', () => {
  const list = [
    inv({ id: 'a' }),
    inv({ id: 'b', dueOn: '2027-01-01', total: 50000 }),
    inv({ id: 'c', status: 'paid' }),
    inv({ id: 'd', status: 'draft' }),
    inv({ id: 'e', status: 'void' }),
  ];
  it('only sent invoices are owed; overdue is past the due date', () => {
    expect(isOverdue(list[0]!, '2026-12-02')).toBe(true);
    expect(isOverdue(list[0]!, '2026-12-01')).toBe(false);
    expect(isOverdue(list[2]!, '2030-01-01')).toBe(false);
    expect(outstanding(list, '2026-12-05')).toEqual({
      count: 2,
      owed: 150000,
      overdueCount: 1,
      overdue: 100000,
    });
  });
  it('the message has the amount, the due date, both ways to pay, and the reference', () => {
    const m = invoiceMessage(list[0]!, 'Alice Fitness', {
      bankDetails: 'FNB 123456',
      paymentLink: 'https://pay.example/a',
      terms: 'Pay before the 1st',
    });
    expect(m).toContain('Hi Dan,');
    expect(m).toContain(
      'AF-202612-001 for your December 2026 sessions is R1 000,00, due Tuesday 1 December 2026',
    );
    expect(m).toContain('Pay online: https://pay.example/a');
    expect(m).toContain('FNB 123456');
    expect(m).toContain('Use AF-202612-001 as the payment reference.');
    expect(m).toContain('Thank you, Alice Fitness');
    expect(invoiceMessage(list[0]!, '', { bankDetails: '', paymentLink: '', terms: '' })).not.toContain(
      'Pay online',
    );
  });
});

describe('database rows', () => {
  const row = (id: string, period: string, number: string) => ({
    id,
    client_id: null,
    client_name: 'X',
    client_email: '',
    number,
    period_start: period,
    issued_on: period,
    due_on: period,
    status: 'draft',
    vat_percent: '15.00',
    subtotal_cents: 100,
    vat_cents: 15,
    total_cents: 115,
    notes: '',
    auto_generated: true,
    email_queued_at: null,
    emailed_at: null,
    paid_at: null,
    paid_method: null,
    invoice_lines: [
      { id: 'l2', position: 1, description: 'B', quantity: '2.00', unit_cents: 50, amount_cents: 100 },
      { id: 'l1', position: 0, description: 'A', quantity: '1', unit_cents: 0, amount_cents: 0 },
    ],
  });
  it('reads invoices newest month first, with lines in order and numbers as numbers', () => {
    const l = parseInvoices([
      row('a', '2026-11-01', 'N-2'),
      row('b', '2026-12-01', 'N-1'),
      row('c', '2026-12-01', 'A-1'),
    ]);
    expect(l.map((x) => x.id)).toEqual(['c', 'b', 'a']);
    expect(l[0]!.vatPercent).toBe(15);
    expect(l[0]!.lines.map((x) => [x.description, x.quantity])).toEqual([
      ['A', 1],
      ['B', 2],
    ]);
    expect(() => parseInvoices([{ ...row('a', '2026-11-01', 'N'), status: 'owing' }])).toThrow();
  });
  it('reads the generation summary, treating empty lists as empty', () => {
    expect(
      parseGenerationSummary({
        month: '2026-12-01',
        generated: 2,
        invoice_ids: ['a', 'b'],
        skipped_no_rate: null,
        skipped_existing: 1,
        skipped_no_sessions: 3,
      }),
    ).toEqual({
      month: '2026-12-01',
      generated: 2,
      invoiceIds: ['a', 'b'],
      skippedNoRate: [],
      skippedExisting: 1,
      skippedNoSessions: 3,
    });
  });
  it('reads the client’s invoices and refuses a draft', () => {
    const p = {
      id: 'i',
      client_id: 'c',
      number: 'N-1',
      period_start: '2026-12-01',
      issued_on: '2026-11-26',
      due_on: '2026-12-01',
      status: 'sent',
      vat_percent: 0,
      subtotal_cents: 100,
      vat_cents: 0,
      total_cents: 100,
      notes: '',
      paid_at: null,
      trainer: {
        business_name: 'AF',
        address: '',
        contact_email: '',
        contact_phone: '',
        bank_details: 'FNB',
        payment_link: '',
        terms: '',
      },
      lines: [{ description: 'S', quantity: 2, unit_cents: 50, amount_cents: 100 }],
    };
    const l = parsePortalInvoices([p]);
    expect(l[0]).toMatchObject({ trainerName: 'AF', total: 100, pay: { bankDetails: 'FNB' } });
    expect(parsePortalInvoices(null)).toEqual([]);
    expect(() => parsePortalInvoices([{ ...p, status: 'draft' }])).toThrow();
  });
});
